#[derive(Debug, thiserror::Error)]
pub enum GpuError {
    #[error("nvidia-smi not found. An NVIDIA GPU with CUDA support is required.")]
    NvidiaSmiMissing,
    #[error("nvidia-smi failed. An NVIDIA GPU with CUDA support is required.")]
    NvidiaSmiFailed,
    #[error(
        "GPU '{name}' has compute capability sm_{actual}, which this solver build does not \
         support. Supported architectures: {supported}. The CUDA kernels ship as native code \
         per architecture with no JIT fallback, so a GPU outside this set cannot run; a newer \
         GPU generation requires a solver rebuild with its architecture added."
    )]
    SmUnsupported {
        name: String,
        actual: u32,
        supported: String,
    },
    #[error("No NVIDIA GPU detected. An NVIDIA GPU is required to run the solver.")]
    NoGpuDetected,
    // THE ADVICE VARIES BY PLATFORM AND THE FIRST SENTENCE DOES NOT. A Windows
    // machine has no amdgpu kernel module, no /dev/kfd and no render group to
    // join, so the Linux wording sent that user looking for device nodes their
    // system cannot have, and the Windows distribution shipped exactly that
    // text. The sentence before the advice is fixed because it travels: the
    // solver prints this as `--probe`'s `unusable:` detail, `frontend._backends_`
    // passes it through verbatim, and the frontend and add-on tests match on it.
    #[error("No AMD GPU detected. {advice}")]
    NoAmdGpuDetected { advice: &'static str },
    #[error(
        "The HIP runtime could not be asked what devices are present (hipError \
         {status}). The runtime ships beside this program, so this usually means the \
         distribution is incomplete rather than that the machine has no GPU."
    )]
    HipRuntimeUnavailable { status: i32 },
    #[error(
        "AMD GPU '{arch}' is not one this solver build ships code for. It ships: \
         {supported}. An AMD code object carries no forward compatibility between gfx \
         numbers, so a part outside this set cannot run and needs a rebuild with its \
         target added. NOTE that this list is what was COMPILED, not what has been \
         tested: this project has no AMD hardware, so no part in it has ever executed \
         a kernel."
    )]
    GfxUnsupported { arch: String, supported: String },
    #[error(
        "CUDA_VISIBLE_DEVICES is set to '{spec}', which selects no GPU this machine has, so \
         CUDA sees no device at all. Detected: {detected}."
    )]
    VisibleDevicesUnsatisfied { spec: String, detected: String },
    #[error(
        "CUDA device 0 cannot be identified from CUDA_VISIBLE_DEVICES='{spec}' on this \
         multi-GPU machine. Select a GPU by UUID. Detected: {detected}."
    )]
    VisibleDeviceAmbiguous { spec: String, detected: String },
    #[error(
        "No Metal-capable GPU detected on this host. MTLCreateSystemDefaultDevice returned no \
         device, so there is no GPU visible to Metal to run the solver on. On real Apple \
         Silicon hardware this should not happen; it is expected only in an environment with no \
         GPU access (for example, some headless CI sandboxes or a VM with no GPU passthrough)."
    )]
    MetalDeviceMissing,
    #[error(
        "GPU '{name}' does not support the Metal GPU family this solver build requires \
         ({required}). This solver's Metal backend targets Apple Silicon Macs only; an Intel \
         Mac with a non-Apple (AMD or Intel integrated) GPU is unsupported, and there is no \
         fallback."
    )]
    MetalFamilyUnsupported { name: String, required: String },
}

/// Position in `rows` of the device CUDA exposes as its own device 0.
///
/// `rows` is `(index, uuid)` per device in the order `nvidia-smi` reported
/// them, and `visible` is the value of `CUDA_VISIBLE_DEVICES`, or `None` when
/// it is not set. Applying that variable is the caller's job: `nvidia-smi`
/// lists every device on the machine whatever the variable says (measured on a
/// four-GPU Windows host, where setting it to `2` still prints rows 0 through
/// 3), so a caller that reads the first row instead describes and validates a
/// GPU the solver may never touch.
///
/// The variable is a comma-separated list and CUDA's device 0 is its first
/// entry, named either by index or by UUID, for which a unique prefix is
/// enough. A value that is empty or all whitespace exposes no device, while
/// `None` leaves visibility unrestricted.
///
/// `None` means the value is absent, ambiguous, or names no detected device.
pub fn visible_device_position(rows: &[(u32, &str)], visible: Option<&str>) -> Option<usize> {
    let Some(spec) = visible else {
        return (rows.len() == 1).then_some(0);
    };
    let selector = spec
        .split(',')
        .next()
        .map(str::trim)
        .filter(|token| !token.is_empty());
    let Some(token) = selector else {
        return None;
    };
    if let Ok(index) = token.parse::<u32>() {
        if rows.len() != 1 {
            return None;
        }
        return rows.iter().position(|&(i, _)| i == index);
    }
    let mut matches = rows
        .iter()
        .enumerate()
        .filter(|(_, (_, uuid))| uuid.starts_with(token));
    let (position, _) = matches.next()?;
    matches.next().is_none().then_some(position)
}

/// One device as `--query-gpu=index,uuid,<fields>,name` reported it.
///
/// Both callers query the identity columns first and `name` last, so a comma
/// inside a marketing name cannot shift the columns that are read by position.
pub struct GpuRow {
    pub index: u32,
    pub uuid: String,
    pub fields: Vec<String>,
    pub name: String,
}

/// Parse `--query-gpu=index,uuid,<field_count fields>,name --format=csv,noheader`.
///
/// A row whose index does not parse, or that is missing columns, is dropped:
/// it carries no device this function can name.
pub fn parse_gpu_rows(stdout: &str, field_count: usize) -> Vec<GpuRow> {
    let mut rows = Vec::new();
    for line in stdout.lines().filter(|l| !l.trim().is_empty()) {
        let parts: Vec<&str> = line.splitn(field_count + 3, ',').collect();
        if parts.len() != field_count + 3 {
            continue;
        }
        let Ok(index) = parts[0].trim().parse::<u32>() else {
            continue;
        };
        rows.push(GpuRow {
            index,
            uuid: parts[1].trim().to_string(),
            fields: parts[2..2 + field_count]
                .iter()
                .map(|f| f.trim().to_string())
                .collect(),
            name: parts[field_count + 2].trim().to_string(),
        });
    }
    rows
}

/// The row of `rows` the solver will run on, honoring `CUDA_VISIBLE_DEVICES`.
pub fn selected_gpu_row(rows: &[GpuRow]) -> Result<&GpuRow, GpuError> {
    if rows.is_empty() {
        return Err(GpuError::NoGpuDetected);
    }
    let visible = std::env::var("CUDA_VISIBLE_DEVICES").ok();
    let pairs: Vec<(u32, &str)> = rows.iter().map(|r| (r.index, r.uuid.as_str())).collect();
    match visible_device_position(&pairs, visible.as_deref()) {
        Some(pos) => Ok(&rows[pos]),
        None => {
            let spec = visible.unwrap_or_default();
            let detected = rows
                .iter()
                .map(|r| format!("{} ({})", r.index, r.name))
                .collect::<Vec<_>>()
                .join(", ");
            let selector = spec.split(',').next().map(str::trim).unwrap_or("");
            if rows.len() > 1 && (selector.is_empty() || selector.parse::<u32>().is_ok()) {
                Err(GpuError::VisibleDeviceAmbiguous { spec, detected })
            } else {
                Err(GpuError::VisibleDevicesUnsatisfied { spec, detected })
            }
        }
    }
}

/// Human-readable rendering of the minimum Metal GPU family gate, for
/// [`GpuError::MetalFamilyUnsupported`] messages.
#[cfg(any(target_os = "macos", test))]
// Dead in a `cpu` build and live in every other one, which is the same shape
// `check_gpu_cuda` is annotated for: `check_gpu` takes its cpu arm first, so
// nothing on macOS reaches the Metal arm or anything it names. A bare `allow`
// would hide a genuine disuse in the builds where this IS reached.
#[cfg_attr(feature = "cpu", allow(dead_code))]
const METAL_MIN_FAMILY_DESC: &str = "Apple7 (the M1 / A14 generation) or newer";

/// Check that a GPU capable of running this solver build is present.
///
/// Dispatches on host platform: the CUDA arm shells out to `nvidia-smi`
/// and gates the selected device on [`SUPPORTED_SM`] cubin coverage; the
/// macOS/Metal arm queries the default Metal device in process and gates
/// on Apple GPU device family, since `nvidia-smi` does not exist on macOS.
///
/// **The `cpu` feature short-circuits both**, and the reason is that the platform
/// is the wrong question for that build. Dispatching on `target_os` alone means a
/// Linux host running the CPU backend is asked for `nvidia-smi` and told "An
/// NVIDIA GPU with CUDA support is required", which is both false and, worse,
/// pre-empts the backend's own message: the CPU backend refuses a scene it cannot
/// solve BY NAME AND BY COUNT at `initialize()`, and that refusal is what the
/// reader needs. A gate in front of it that names a different, wrong reason
/// converts a precise diagnosis into a misleading one. Measured: every one of the
/// 24 example notebooks died here, none of them reaching the backend at all.
///
/// This is a capability question, so the flag is owned by this crate and
/// dependents cascade `cpu = ["ppf-cts-core/cpu"]`. A single toggle keeps the
/// definitions from drifting.
/// Whether this build needs an NVIDIA driver, and therefore whether the
/// driver-version check and the `nvidia-smi` diagnostic dumps apply.
///
/// It exists because the frontend was asking the PLATFORM instead. Gating on
/// `platform.system() != "Darwin"` is right for exactly two of the four backends
/// and wrong for the CPU one on Linux, where it demands an NVIDIA driver version
/// from a build that will never launch a CUDA kernel. That is the same mistake
/// [`check_gpu`] made, in a different language, so the answer is published once
/// here rather than re-derived per caller.
///
/// A capability, not a platform: read it as "does this build talk to CUDA",
/// which is what every caller actually wants to know.
pub fn needs_nvidia_driver() -> bool {
    // A ROCm build needs the AMD kernel driver and `/dev/kfd`, not an NVIDIA
    // one, so it answers NO here for the same reason the CPU build does. The
    // answer is published from this one function rather than recomputed in
    // Python, which is why the flag has to reach it rather than being handled
    // only at the call site.
    !cfg!(feature = "cpu")
        && !cfg!(feature = "rocm")
        && !cfg!(target_os = "macos")
}

pub fn check_gpu() -> Result<(), GpuError> {
    #[cfg(feature = "cpu")]
    {
        Ok(())
    }
    #[cfg(all(not(feature = "cpu"), not(feature = "rocm"), target_os = "macos"))]
    {
        check_gpu_metal()
    }
    // THE ROCm ARM MUST NOT BE `rocminfo`, and that is a packaging constraint
    // rather than a preference: `rocminfo` is a ROCm package, so reaching for it
    // would put a ROCm installation back in front of an end user, which is the
    // one thing the distribution exists to avoid. The device query belongs in an
    // in-process probe against the BUNDLED runtime, the shape `check_gpu_metal`
    // already has, and that is what `check_gpu_rocm` below is. The alternative
    // this rules out is not just `rocminfo`: a preflight that asked `nvidia-smi`
    // would refuse every correct ROCm machine, which is what the non-macOS
    // default arm does and why ROCm needs its own.
    #[cfg(all(
        not(feature = "cpu"),
        feature = "rocm",
        any(target_os = "linux", target_os = "windows")
    ))]
    {
        check_gpu_rocm()
    }
    // NOTHING ELSE RUNS ROCm, so this arm is macOS and whatever else cargo is
    // pointed at. It admits rather than refusing: there is no HIP runtime to
    // ask, and the backend's own `be_open` fails by name if such a build is ever
    // produced and run.
    #[cfg(all(
        not(feature = "cpu"),
        feature = "rocm",
        not(any(target_os = "linux", target_os = "windows"))
    ))]
    {
        Ok(())
    }
    #[cfg(all(not(feature = "cpu"), not(feature = "rocm"), not(target_os = "macos")))]
    {
        check_gpu_cuda()
    }
}

// The ROCm probe compiled by this crate's `build.rs` from `cpp/rocm_probe.cpp`,
// against the SDK's own headers. Declared here rather than mirrored: see that
// file's header for why `hipDeviceProp_t` may not be re-declared. A plain
// comment, not a doc comment: rustdoc documents no extern block, so `///` here
// is an `unused_doc_comments` warning rather than documentation.
#[cfg(all(
    not(feature = "cpu"),
    feature = "rocm",
    any(target_os = "linux", target_os = "windows")
))]
extern "C" {
    fn ppf_cts_core_rocm_probe(
        out_count: *mut std::ffi::c_int,
        out_arch: *mut std::ffi::c_char,
        out_arch_cap: usize,
        out_status: *mut std::ffi::c_int,
    ) -> std::ffi::c_int;
}

/// ROCm arm of [`check_gpu`]: asks the BUNDLED HIP runtime in process, with no
/// subprocess and no ROCm installation.
///
/// **IT MUST NOT BE `rocminfo`**, which is a ROCm package: reaching for it would
/// put an installation back in front of an end user, which is the one thing the
/// distribution exists to avoid. The runtime this calls is the one shipped
/// beside the binary.
///
/// **AND IT GATES ON THE ARCHITECTURE ONLY ON THE AMD PLATFORM.** An
/// `HIP_PLATFORM=nvidia` build is the staging leg: HIP is a shim over CUDA
/// there, the device is an NVIDIA GPU, and `SUPPORTED_GFX` describes nothing it
/// runs, so gating on it would refuse every machine that build targets. The
/// platform is published as a cfg by `build.rs` rather than guessed here.
#[cfg(all(
    not(feature = "cpu"),
    feature = "rocm",
    any(target_os = "linux", target_os = "windows")
))]
fn check_gpu_rocm() -> Result<(), GpuError> {
    let reported = rocm_probe()?;
    // The staging platform reports a device NAME here, not a gfx target, so
    // there is nothing for SUPPORTED_GFX to say about it.
    #[cfg(rocm_platform_nvidia)]
    {
        let _ = reported;
        return Ok(());
    }
    #[cfg(not(rocm_platform_nvidia))]
    {
        if gfx_is_supported(&reported) {
            Ok(())
        } else {
            Err(GpuError::GfxUnsupported {
                arch: reported,
                supported: supported_gfx_list(),
            })
        }
    }
}

/// Ask the bundled HIP runtime for its first device and return what that device
/// calls itself: the gfx target on the AMD platform, the device name on the
/// staging one. [`check_gpu_rocm`] gates on the answer and
/// [`rocm_device_arch`] reports it.
#[cfg(all(
    not(feature = "cpu"),
    feature = "rocm",
    any(target_os = "linux", target_os = "windows")
))]
fn rocm_probe() -> Result<String, GpuError> {
    const CAP: usize = 256;
    let mut count: std::ffi::c_int = 0;
    let mut status: std::ffi::c_int = 0;
    let mut arch = [0 as std::ffi::c_char; CAP];
    // SAFETY: the three out pointers address live locals for the whole call and
    // the probe writes at most CAP bytes into `arch`, NUL-terminating within it.
    let rc = unsafe {
        ppf_cts_core_rocm_probe(&mut count, arch.as_mut_ptr(), CAP, &mut status)
    };
    if rc != 0 {
        return Err(GpuError::HipRuntimeUnavailable { status: status as i32 });
    }
    if count <= 0 {
        // A MACHINE WITH NO AMD GPU ARRIVES HERE RATHER THAN FAILING TO LOAD, on
        // Windows especially: `amdhip64_7.dll` loads without an AMD driver
        // (measured on a Windows machine with no AMD GPU, which is why
        // bundle.bat's import gate can load the ROCm cdylib there), so the
        // runtime answers "zero devices"
        // instead of the program failing to start. That makes this message the
        // only thing such a user sees, so it names what they can act on.
        return Err(GpuError::NoAmdGpuDetected {
            advice: if cfg!(target_os = "windows") {
                "This is a ROCm build, so it needs an AMD GPU with AMD's Windows \
                 driver installed. No ROCm installation is required: the runtime \
                 ships with this program."
            } else {
                "This is a ROCm build, so it needs an AMD GPU with the amdgpu \
                 kernel driver loaded and /dev/kfd present, and the user running \
                 it must be in the group that owns /dev/kfd and /dev/dri/render*. \
                 No ROCm installation is required: the runtime ships with this \
                 program."
            },
        });
    }
    // SAFETY: the probe NUL-terminated `arch` within CAP on the success path.
    Ok(unsafe { std::ffi::CStr::from_ptr(arch.as_ptr()) }
        .to_string_lossy()
        .into_owned())
}

/// What the first AMD device calls itself, for a hardware report, or `None`
/// when this build has no HIP runtime to ask or the runtime reports no device.
///
/// A REPORT, NOT A GATE: [`check_gpu`] is what refuses a run. It is declared on
/// every build so a caller matching on [`backend`] can name it in the `Rocm`
/// arm without a feature of its own, and only a ROCm build reaches that arm.
pub fn rocm_device_arch() -> Option<String> {
    #[cfg(all(
        not(feature = "cpu"),
        feature = "rocm",
        any(target_os = "linux", target_os = "windows")
    ))]
    {
        rocm_probe().ok()
    }
    #[cfg(not(all(
        not(feature = "cpu"),
        feature = "rocm",
        any(target_os = "linux", target_os = "windows")
    )))]
    {
        None
    }
}

/// CUDA arm of [`check_gpu`]: asks `nvidia-smi` for `index,uuid,compute_cap,name`
/// with `CUDA_VISIBLE_DEVICES` removed from the subprocess environment, so every
/// device on the machine is enumerated, then applies that variable in code (see
/// [`selected_gpu_row`]) and gates the row the solver will actually launch on
/// against [`SUPPORTED_SM`] cubin coverage.
///
/// Its one caller is [`check_gpu`], which selects this arm only when neither the
/// `cpu` nor the `rocm` feature is on, while the `cfg` on this function admits
/// it on target alone. A `cpu` or `rocm` build therefore compiles it with no
/// call site, a ROCm machine needing the AMD kernel driver rather than an
/// NVIDIA one. No test calls it either: the tests cover the pieces it composes,
/// `parse_gpu_rows`, `selected_gpu_row`, `sm_is_supported` and the error
/// strings, rather than the `nvidia-smi` subprocess it runs.
#[cfg_attr(any(feature = "cpu", feature = "rocm"), allow(dead_code))]
#[cfg(not(target_os = "macos"))]
fn check_gpu_cuda() -> Result<(), GpuError> {
    let output = match Command::new("nvidia-smi")
        .args([
            "--query-gpu=index,uuid,compute_cap,name",
            "--format=csv,noheader,nounits",
        ])
        // Enumerate every device and apply CUDA_VISIBLE_DEVICES in code; see
        // `visible_device_position` for why nvidia-smi's own handling of it is
        // not relied on.
        .env_remove("CUDA_VISIBLE_DEVICES")
        .output()
    {
        Ok(o) => o,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            return Err(GpuError::NvidiaSmiMissing);
        }
        Err(_) => {
            return Err(GpuError::NvidiaSmiFailed);
        }
    };
    if !output.status.success() {
        return Err(GpuError::NvidiaSmiFailed);
    }
    let stdout = String::from_utf8_lossy(&output.stdout);
    let rows = parse_gpu_rows(&stdout, 1);
    // Validate the GPU the solver will actually launch on, which is the one
    // CUDA_VISIBLE_DEVICES selects, not the first row nvidia-smi prints. On a
    // machine whose first GPU is a display adapter below SUPPORTED_SM, reading
    // row 0 rejects a run that the selected compute card could serve.
    let selected = selected_gpu_row(&rows)?;
    let sm_ver = match selected.fields[0].replace('.', "").parse::<u32>() {
        Ok(v) => v,
        Err(_) => return Err(GpuError::NvidiaSmiFailed),
    };
    if !sm_is_supported(sm_ver) {
        return Err(GpuError::SmUnsupported {
            name: selected.name.clone(),
            actual: sm_ver,
            supported: supported_sm_list(),
        });
    }
    Ok(())
}

// Runtime probe compiled by build.rs from cpp/metal_probe.mm, linked
// only on macOS (see build.rs). Deliberately narrow: this is a
// pre-flight capability query, not a copy of the real Metal backend's
// own device setup in crates/ppf-cts-compute/metal/.
#[cfg(target_os = "macos")]
#[cfg_attr(feature = "cpu", allow(dead_code))]
extern "C" {
    fn ppf_cts_core_metal_probe(
        out_device_found: *mut bool,
        out_family_ok: *mut bool,
        out_name: *mut std::os::raw::c_char,
        out_name_cap: std::os::raw::c_ulong,
    );
}

/// Metal arm of [`check_gpu`]: queries the default Metal device directly, with
/// no subprocess, and gates on Apple GPU family membership. Runtime resource
/// limits remain the backend context's responsibility because they apply to
/// individual pipelines and allocations rather than this preflight check.
#[cfg(target_os = "macos")]
#[cfg_attr(feature = "cpu", allow(dead_code))]
fn check_gpu_metal() -> Result<(), GpuError> {
    const NAME_CAP: usize = 256;
    let mut device_found = false;
    let mut family_ok = false;
    let mut name_buf = [0 as std::os::raw::c_char; NAME_CAP];
    // Safety: `device_found`/`family_ok` are live `bool` locals on this
    // stack frame, and `name_buf` is a live `NAME_CAP`-byte buffer whose
    // capacity is passed alongside it; the C probe never writes past
    // `out_name_cap` bytes and always NUL-terminates within it.
    unsafe {
        ppf_cts_core_metal_probe(
            &mut device_found,
            &mut family_ok,
            name_buf.as_mut_ptr(),
            NAME_CAP as std::os::raw::c_ulong,
        );
    }
    if !device_found {
        return Err(GpuError::MetalDeviceMissing);
    }
    if !family_ok {
        // Safety: the probe always NUL-terminates `name_buf` within its
        // capacity, even on the found-but-unsupported-family path.
        let name = unsafe { std::ffi::CStr::from_ptr(name_buf.as_ptr()) }
            .to_string_lossy()
            .into_owned();
        return Err(GpuError::MetalFamilyUnsupported {
            name,
            required: METAL_MIN_FAMILY_DESC.to_string(),
        });
    }
    Ok(())
}


/// Which backend a build targets.
///
/// AN ENUM RATHER THAN A STRING, so a caller deciding what to probe writes an
/// exhaustive match and a fourth backend cannot be added without every such
/// caller being made to say what it does about it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Backend {
    Cuda,
    Metal,
    Rocm,
    Cpu,
}

impl Backend {
    /// The lowercase word for this backend.
    ///
    /// These match `PPF_BACKEND` in `ppf-cts-solver`, which is what
    /// `ppf-contact-solver --backend` prints and what the `.ppf-backend` marker
    /// beside the artifacts holds, so a reader comparing what a panel says
    /// against either of those gets the same word.
    pub fn name(self) -> &'static str {
        match self {
            Backend::Cuda => "cuda",
            Backend::Metal => "metal",
            Backend::Rocm => "rocm",
            Backend::Cpu => "cpu",
        }
    }
}

/// Which backend THIS build targets.
///
/// The arms are [`check_gpu`]'s, deliberately: a build that asks for an NVIDIA
/// device is the same build that reports CUDA, and a build that asks the HIP
/// runtime is the one that reports ROCm, so deriving both from one set of
/// `cfg`s is what stops a panel naming a backend the preflight would refuse.
/// Without the ROCm arm a ROCm server reported itself as `cuda` and asked
/// `nvidia-smi` for its hardware rows.
///
/// The server cannot ask the SOLVER binary instead, which would be the rule
/// elsewhere in this tree. It never resolves that path: the frontend spawns the
/// solver, so at the moment the server probes its hardware there is no artifact
/// here to interrogate.
pub fn backend() -> Backend {
    #[cfg(feature = "cpu")]
    {
        Backend::Cpu
    }
    #[cfg(all(not(feature = "cpu"), feature = "rocm"))]
    {
        Backend::Rocm
    }
    #[cfg(all(not(feature = "cpu"), not(feature = "rocm"), target_os = "macos"))]
    {
        Backend::Metal
    }
    #[cfg(all(not(feature = "cpu"), not(feature = "rocm"), not(target_os = "macos")))]
    {
        Backend::Cuda
    }
}

/// What the default Metal device calls itself, and how much memory it will
/// work with.
#[cfg(target_os = "macos")]
pub struct MetalDeviceInfo {
    /// The device's own localized name, for example `Apple M2 Max`.
    pub name: String,
    /// `recommendedMaxWorkingSetSize`, in bytes. Apple Silicon has no separate
    /// VRAM, memory being unified with the CPU, so this is the working set
    /// Metal recommends staying under rather than a card's capacity.
    pub working_set_bytes: u64,
    /// The highest `MTLGPUFamilyApple<N>` the device supports, as N, or `None`
    /// when it supports no Apple family at all. This is the Metal analogue of a
    /// CUDA SM level, and the same number [`check_gpu`] gates on: Apple7 is the
    /// minimum the backend targets, so a device reporting `None` here is one
    /// that preflight refuses.
    pub apple_family: Option<u32>,
}

// Descriptive companion to `ppf_cts_core_metal_probe`, compiled from the same
// cpp/metal_probe.mm. Kept separate there so a failure feeding a panel can
// never reach what the preflight decides.
#[cfg(target_os = "macos")]
extern "C" {
    fn ppf_cts_core_metal_device_info(
        out_name: *mut std::os::raw::c_char,
        out_name_cap: std::os::raw::c_ulong,
        out_working_set_bytes: *mut u64,
        out_apple_family: *mut std::os::raw::c_uint,
    ) -> bool;
}

/// A live sample of what the GPU is doing, for the "Realtime Statistics" rows.
#[cfg(target_os = "macos")]
pub struct MetalUsage {
    /// System-wide GPU utilization, 0 to 100. The counter Activity Monitor
    /// shows, and like nvidia-smi's it describes the DEVICE rather than this
    /// process.
    pub device_util_pct: u32,
    /// Bytes of system memory the accelerator currently has in use, or `None`
    /// when the registry did not publish that key.
    pub in_use_bytes: Option<u64>,
}

// The live counter, read from the IOAccelerator registry entry rather than from
// Metal, which publishes no device-wide utilization figure.
#[cfg(target_os = "macos")]
extern "C" {
    fn ppf_cts_core_metal_usage(
        out_device_util_pct: *mut std::os::raw::c_uint,
        out_in_use_bytes: *mut u64,
    ) -> bool;
}

/// Sample the GPU's current utilization, or `None` when no counter could be
/// read.
///
/// CALLED ON EVERY STATUS POLL, so it does no subprocess work: the CUDA side
/// spawns nvidia-smi for the same answer, and this is a registry read in
/// process. `None` here means the rows are omitted, never that anything failed
/// loudly, because the keys it reads are registry properties rather than
/// published API and a macOS that renames one must cost a row and nothing more.
#[cfg(target_os = "macos")]
pub fn metal_usage() -> Option<MetalUsage> {
    let mut pct: std::os::raw::c_uint = 0;
    let mut in_use: u64 = 0;
    // Safety: both are live locals on this stack frame, and the probe writes
    // each at most once through the pointer it was given.
    let found = unsafe { ppf_cts_core_metal_usage(&mut pct, &mut in_use) };
    if !found {
        return None;
    }
    Some(MetalUsage {
        device_util_pct: pct as u32,
        in_use_bytes: (in_use > 0).then_some(in_use),
    })
}

/// Describe the default Metal device, or `None` when there is no such device.
///
/// PURELY DESCRIPTIVE, AND NOTHING GATES ON IT. `check_gpu` is what decides
/// whether this host may run; this only says what the panel shows. So a `None`
/// here means a row is omitted, never that a run is refused.
#[cfg(target_os = "macos")]
pub fn metal_device_info() -> Option<MetalDeviceInfo> {
    const NAME_CAP: usize = 256;
    let mut name_buf = [0 as std::os::raw::c_char; NAME_CAP];
    let mut working_set_bytes: u64 = 0;
    let mut apple_family: std::os::raw::c_uint = 0;
    // Safety: `name_buf` is a live NAME_CAP-byte buffer whose capacity is
    // passed alongside it and which the probe always NUL-terminates within, and
    // `working_set_bytes` and `apple_family` are live locals on this stack
    // frame.
    let found = unsafe {
        ppf_cts_core_metal_device_info(
            name_buf.as_mut_ptr(),
            NAME_CAP as std::os::raw::c_ulong,
            &mut working_set_bytes,
            &mut apple_family,
        )
    };
    if !found {
        return None;
    }
    // Safety: NUL-terminated within capacity by the probe, on every path that
    // reports a device.
    let name = unsafe { std::ffi::CStr::from_ptr(name_buf.as_ptr()) }
        .to_string_lossy()
        .into_owned();
    Some(MetalDeviceInfo {
        name,
        working_set_bytes,
        // Zero is the probe's "no Apple family at all", which is a real answer
        // about the device rather than a failure, so it becomes None here and
        // the row is simply not drawn.
        apple_family: (apple_family > 0).then_some(apple_family as u32),
    })
}

