// Cache directory.

/// Platform-aware cache directory for the tree at `base_dir`.
///
/// ONE RESOLVER, NOT TWO. This delegates to
/// `datamodel::app::default_cache_dir` rather than answering the same question
/// with its own code. A second implementation anchored at `current_dir()` would
/// agree with it only while the caller happened to have chdir'd to the tree
/// root; sharing one implementation is what puts a packaged tree's export, CI
/// and render-temp directories beside its asset cache instead of in `$HOME`.
///
/// `base_dir` is the tree root, the same value `App.get_data_dirpath` passes.
/// The Python bindings resolve it from `frontend/__file__`, which is the only
/// place that reliably knows it: `current_dir()` is wherever the user happened
/// to run from, and a cdylib's `current_exe()` is the interpreter.
pub fn get_cache_dir(base_dir: &Path) -> PathBuf {
    let home = std::env::var_os("HOME").map(PathBuf::from);
    let dir = crate::datamodel::app::default_cache_dir(base_dir, home.as_deref());
    let _ = std::fs::create_dir_all(&dir);
    dir
}

