/// Process-name substring the solver binary advertises. Both
/// `solver_busy` and `terminate_solver` filter on this.
pub const SOLVER_PROCESS_NAME: &str = "ppf-contact";

/// Compute-capability targets (encoded `major*10 + minor`, so sm_86 == 86 and
/// sm_120 == 120) for which the CUDA solver ships a native SASS cubin. Device
/// LTO embeds no JIT-able PTX, so a GPU with no matching cubin cannot launch
/// any kernel; `check_gpu` gates launches against this list.
///
/// Generated by this crate's `build.rs` from
/// `crates/ppf-cts-compute/cuda/cuda_arch.txt`, which is also what both CUDA
/// builds derive their `-gencode` lines from. So this is not a copy that has to
/// be kept in step with the build, it is the same list, and editing the
/// manifest moves the build and this gate together. `ppf-cts-solver`'s
/// `build.rs` separately checks the built image against that manifest, which
/// covers the case where the toolchain did not emit what it was asked for.
pub const SUPPORTED_SM: &[u32] =
    &include!(concat!(env!("OUT_DIR"), "/cuda_arch_cubins.rs"));

/// True iff the solver ships a cubin that can run natively on a device of
/// compute capability `sm` (encoded `major*10 + minor`). SASS is binary
/// compatible forward within a major version only, so a shipped cubin `c` runs
/// on device `d` iff they share a major version and `c`'s minor `<=` `d`'s minor
/// (e.g. the sm_86 cubin also covers sm_87 and sm_89, but not sm_80). A brand
/// new major version, or a minor below every cubin we ship for that major, is
/// unsupported until a cubin is added and the solver is rebuilt.
pub fn sm_is_supported(sm: u32) -> bool {
    SUPPORTED_SM
        .iter()
        .any(|&c| c / 10 == sm / 10 && c % 10 <= sm % 10)
}

/// The AMD parts the ROCm solver ships native code objects for, as the names a
/// device reports: `gfx1100`, never `gfx11-generic`.
///
/// **A DEVICE NEVER NAMES A GENERIC TARGET, WHICH IS WHY THIS LIST IS EXPANDED
/// RATHER THAN COPIED.** `hipDeviceProp_t::gcnArchName` gives a specific part,
/// while `rocm_arch.txt` is mostly generic targets, each emitting one code
/// object for a whole family. `build.rs` expands the first through
/// `crates/ppf-cts-compute/rocm/generic_targets.txt`, whose membership is read
/// from the pinned toolchain's own documentation rather than assumed; that file
/// records the commit and why guessing is wrong in both directions.
///
/// **THIS IS A COMPILE-COVERAGE CLAIM AND NOT A TESTED-HARDWARE CLAIM.** No AMD
/// Radeon hardware is available to this project, so nothing in this list has
/// ever executed a kernel. Any refusal built on it must therefore be worded so a
/// user cannot read it as the second.
pub const SUPPORTED_GFX: &[&str] =
    &include!(concat!(env!("OUT_DIR"), "/rocm_arch_gfx.rs"));

/// True iff the solver ships a code object that runs natively on a device whose
/// `gcnArchName` is `arch`.
///
/// **THE COMPARISON DROPS THE TARGET-ID FEATURES AND KEEPS THE PART.** A real
/// device reports its architecture with the feature flags appended,
/// `gfx90a:sramecc+:xnack-`, and those describe the mode the device is in rather
/// than which code object can run on it. Matching the whole string would refuse
/// every machine that has xnack enabled, which is most of them on the parts that
/// support it. Everything from the first `:` is therefore cut before the
/// comparison, and the remainder must match a shipped part exactly: unlike CUDA
/// SASS, an AMD code object is not forward compatible within a family, which is
/// the whole reason the generic targets exist.
pub fn gfx_is_supported(arch: &str) -> bool {
    let part = arch.split(':').next().unwrap_or(arch).trim();
    SUPPORTED_GFX.iter().any(|&c| c == part)
}

/// Human-readable `gfx1100, gfx1101, ...` rendering of [`SUPPORTED_GFX`] for
/// error messages, on the same terms as [`supported_sm_list`].
#[cfg_attr(
    any(target_os = "macos", feature = "cpu"),
    allow(dead_code)
)]
pub fn supported_gfx_list() -> String {
    SUPPORTED_GFX.join(", ")
}

/// Human-readable `sm_86, sm_89, ...` rendering of [`SUPPORTED_SM`] for error
/// messages. Only reachable from non-test code via `check_gpu_cuda`, so a
/// non-test build sees no call site wherever that arm is `cfg`'d out: on macOS,
/// under the `cpu` feature, and under `rocm`, in all of which [`check_gpu`]
/// returns before reaching the CUDA arm.
///
/// What reads it in those configurations is the test
/// `check_gpu_error_messages_match_python` in this file's `tests` module, which
/// pins the `SmUnsupported` message and asserts that the supported set is
/// spelled out in it, so dropping the rendering costs that message the list a
/// user needs in order to act on it.
#[cfg_attr(
    any(target_os = "macos", feature = "cpu", feature = "rocm"),
    allow(dead_code)
)]
fn supported_sm_list() -> String {
    SUPPORTED_SM
        .iter()
        .map(|s| format!("sm_{s}"))
        .collect::<Vec<_>>()
        .join(", ")
}

