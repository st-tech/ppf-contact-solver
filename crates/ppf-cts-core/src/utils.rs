/// Construct and populate a `System` snapshot scoped to process info.
/// All three process helpers read only name/status/parent, so a
/// process-only refresh is sufficient. Centralizing the construction
/// keeps the refresh decision in one place.
fn scan_solver_system() -> System {
    let mut sys = System::new_with_specifics(
        RefreshKind::new().with_processes(ProcessRefreshKind::new()),
    );
    sys.refresh_processes(ProcessesToUpdate::All, true);
    sys
}

/// True iff `proc` is a live (non-zombie) solver process, i.e. its
/// name contains `SOLVER_PROCESS_NAME`.
fn is_live_solver(proc: &sysinfo::Process) -> bool {
    proc.name().to_string_lossy().contains(SOLVER_PROCESS_NAME)
        && !matches!(proc.status(), sysinfo::ProcessStatus::Zombie)
}

/// Whether this process has been told it is one worker among several on the
/// host, so a solver scan must see only its OWN descendants.
///
/// THE SCOPING COMES FROM A RUNTIME SIGNAL, WHICH IS THE WHOLE POINT.
/// `ppf-cts-server`'s monitor and executor both record that the descendant-only
/// pair is what a multi-worker runner has to be re-keyed onto, and that the
/// signal cannot be a build feature: no backend has a flag standing in for
/// "under a parallel runner". An environment variable is a property of the
/// PROCESS, which is exactly the granularity the question has.
///
/// Unset is the default and is host-global, which is the conservative answer: a
/// single-worker host wants to know about any solver at all, and two scopings
/// agree there.
pub fn worker_scoped_scan() -> bool {
    std::env::var_os("PPF_SOLVER_SCAN_DESCENDANTS").is_some()
}

/// True iff a live solver process is running.
///
/// Host-global by default; own-descendants-only when
/// `PPF_SOLVER_SCAN_DESCENDANTS` is set, so several workers can run on one host
/// without each reporting the others' solvers as its own.
pub fn solver_busy() -> bool {
    if worker_scoped_scan() {
        return solver_busy_descendants_only();
    }
    let sys = scan_solver_system();
    sys.processes().values().any(is_live_solver)
}

/// Collect the PIDs of every live (non-zombie) solver process that is
/// a descendant of the current process, given an already-refreshed
/// `System` snapshot. Shared by `solver_busy_descendants_only` and
/// `terminate_solver_descendants_only` so the descendant-tree walk
/// can't drift between the busy check and the kill. The current
/// process (``me``) is never included even if it somehow matched.
fn solver_descendant_pids(sys: &System) -> Vec<sysinfo::Pid> {
    let me = sysinfo::Pid::from_u32(std::process::id());
    let processes = sys.processes();
    // Build a parent->child map so we can walk the descendant tree
    // in a single pass. ``Process::parent`` only gives us one edge,
    // so the loop has to start from ``me`` and follow children.
    let mut children_of: std::collections::HashMap<sysinfo::Pid, Vec<sysinfo::Pid>> =
        std::collections::HashMap::new();
    for (pid, proc) in processes.iter() {
        if let Some(parent) = proc.parent() {
            children_of.entry(parent).or_default().push(*pid);
        }
    }
    let mut matches: Vec<sysinfo::Pid> = Vec::new();
    let mut stack: Vec<sysinfo::Pid> = vec![me];
    let mut seen: std::collections::HashSet<sysinfo::Pid> = std::collections::HashSet::new();
    while let Some(pid) = stack.pop() {
        if !seen.insert(pid) {
            continue;
        }
        if let Some(proc) = processes.get(&pid) {
            if pid != me && is_live_solver(proc) {
                matches.push(pid);
            }
        }
        if let Some(kids) = children_of.get(&pid) {
            stack.extend(kids.iter().copied());
        }
    }
    matches
}

/// True iff any **descendant** of the current process whose name
/// contains `SOLVER_PROCESS_NAME` is running and not a zombie, so a peer
/// worker's solver (running on the same host but in a different process
/// tree) does not trip our own "solver already running" guard.
///
/// LIVE, AND SELECTED AT RUNTIME. [`solver_busy`] calls this whenever
/// `worker_scoped_scan()` reads `PPF_SOLVER_SCAN_DESCENDANTS`, so the selector
/// is a runtime signal rather than a build-time one.
/// The race it answers is a property of running several workers on one host and
/// not of any backend. Re-key [`terminate_solver_descendants_only`] in the same
/// change, never one alone: the kill set and the check set have to agree.
pub fn solver_busy_descendants_only() -> bool {
    let sys = scan_solver_system();
    !solver_descendant_pids(&sys).is_empty()
}

